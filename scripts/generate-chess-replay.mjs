// Turns the PGN below into the move data src/chess-replay.js plays back on the
// Quality Knights card.
//
// The conversion happens here, at build time, rather than in the browser: SAN
// ("Nxe6", "O-O", "exd5") doesn't say which piece moved from where, so reading
// it back requires full legal-move generation — castling, en passant,
// promotion, disambiguating two knights that can both reach a square. That is
// chess.js's job, and chess.js is a devDependency precisely so it never has to
// ship to a reader. What ships is the answer: for each ply, the squares the
// piece left and arrived at, and the whole board as it stood afterwards.
//
// Emitting the full position per ply (not just from/to) is what keeps the
// runtime honest. The slide animation only has to be pretty; the position that
// lands after it is authoritative, so castling moves the rook, en passant
// clears the captured pawn and a promotion arrives as a queen without the
// player knowing any of those rules exist.
//
// Re-run after changing the game:
//   node scripts/generate-chess-replay.mjs
import { Chess } from 'chess.js';
import { writeFileSync } from 'node:fs';

// Carlsen–Nakamura, Chess.com Speed Chess Championship final, 22 September
// 2023 — a Berlin that Nakamura grinds out a pawn up. Source:
// https://www.chessgames.com/perl/chessgame?gid=2574400
// A blitz game rather than one of their classical meetings, because the card
// it sits on is about chess played on a lunch break.
const PGN = `[Event "Chess.com Speed Chess Championship"]
[Site "Chess.com INT"]
[Date "2023.09.22"]
[Result "0-1"]
[White "Magnus Carlsen"]
[Black "Hikaru Nakamura"]
[ECO "C67"]

1. e4 e5 2. Nf3 Nc6 3. Bb5 Nf6 4. O-O Nxe4 5. d4 Nd6 6. Bxc6 dxc6 7. dxe5 Nf5
8. Qxd8+ Kxd8 9. Nc3 Bd7 10. h3 Kc8 11. b3 h6 12. Bb2 b6 13. Ne2 a5 14. Nf4 a4
15. e6 Bxe6 16. Nxe6 fxe6 17. Rfe1 Rg8 18. Rxe6 g5 19. g4 Nd6 20. Kg2 Kb7
21. Be5 axb3 22. axb3 Re8 23. Rxe8 Nxe8 24. Re1 c5 25. h4 gxh4 26. Kh3 Nd6
27. Nxh4 h5 28. gxh5 Rg5 29. Ng6 Bh6 30. Bf4 Rxh5+ 31. Kg4 Rf5 32. Bxd6 Rg5+
33. Kh4 cxd6 34. Re6 Rg2 35. Rxd6 Rxf2 36. c4 Rb2 37. Ne7 Bf4 38. Rd7+ Ka8
39. Nc6 Bb8 40. Rd8 Kb7 41. Nxb8 Rxb3 42. Kg5 Rc3 43. Rh8 Kc7 44. Kf5 Rxc4
45. Ke6 Rd4 46. Ke5 Rd1 47. Na6+ Kb7 48. Nb8 c4 49. Ke6 c3 50. Nd7 c2
51. Rb8+ Kc7 0-1`;

const OUT = 'src/chess-replay-game.js';

// a8 is index 0 and h1 is index 63, so the string reads the way the board is
// drawn: left to right, top to bottom, from White's side of the table.
const placement = (chess) =>
  chess
    .board()
    .flat()
    .map((sq) => (sq === null ? '.' : sq.color === 'w' ? sq.type.toUpperCase() : sq.type))
    .join('');

const chess = new Chess();
chess.loadPgn(PGN);
const headers = chess.getHeaders();
const moves = chess.history({ verbose: true });

// history() is the finished game, so replay it from the start to capture the
// position standing after each ply.
const replay = new Chess();
const start = placement(replay);
const plies = moves.map((move) => {
  replay.move(move.san);
  return [move.san, move.from, move.to, placement(replay)];
});

// Single quotes and one ply per line, so the generated file is already in the
// house Prettier style and `prettier --check .` stays green without anyone
// having to remember to reformat it. A ply is a tuple rather than an object
// purely to fit the 100-column line limit: an object with four named keys and
// a 64-character board does not, and Prettier would explode every one of the
// hundred-odd plies across six lines.
const q = (s) => `'${s}'`;
const file = `// Generated by scripts/generate-chess-replay.mjs — do not edit by hand.
// ${headers.White} vs ${headers.Black}, ${headers.Event}, ${headers.Date}, ${headers.Result}.
// Each ply is [SAN, from, to, board]: the square the moving piece left, the
// one it arrived at, and the whole position afterwards as 64 characters —
// a8 first and h1 last, FEN letters for the pieces, '.' for an empty square.
export const GAME = {
  white: ${q(headers.White)},
  black: ${q(headers.Black)},
  event: ${q(headers.Event)},
  date: ${q(headers.Date)},
  result: ${q(headers.Result)},
  start: ${q(start)},
  plies: [
${plies.map((p) => `    [${p.map(q).join(', ')}],`).join('\n')}
  ],
};
`;

writeFileSync(OUT, file);
console.log(
  `${OUT}: ${headers.White} vs ${headers.Black}, ${plies.length} plies, result ${headers.Result}`,
);
